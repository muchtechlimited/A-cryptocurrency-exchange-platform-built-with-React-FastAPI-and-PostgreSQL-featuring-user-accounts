import uuid
from datetime import datetime
from decimal import Decimal
from typing import Literal, Optional

from pydantic import BaseModel, Field


class BillNetworkOut(BaseModel):
    id: str
    label: str


class BillConfigOut(BaseModel):
    available: bool                      # false = feature off or provider not set up: hide the buy buttons
    networks: list[BillNetworkOut]
    airtime_min: int
    airtime_max: int


class BillPlanOut(BaseModel):
    id: uuid.UUID
    network: str
    name: str
    selling_price: Decimal

    model_config = {"from_attributes": True}


class AirtimePurchase(BaseModel):
    network: str
    phone: str = Field(min_length=10, max_length=20)
    amount: Decimal = Field(gt=0, le=1_000_000)
    client_ref: str = Field(min_length=8, max_length=64)   # generated by the app per purchase attempt; makes retries safe


class DataPurchase(BaseModel):
    network: str
    phone: str = Field(min_length=10, max_length=20)
    plan_id: uuid.UUID
    client_ref: str = Field(min_length=8, max_length=64)


class BillOrderOut(BaseModel):
    id: uuid.UUID
    category: str
    network: str
    phone: str
    plan_name: Optional[str] = None
    amount: Decimal
    status: str                          # processing | completed | failed (refunded)
    created_at: datetime
    completed_at: Optional[datetime] = None
    refunded_at: Optional[datetime] = None

    model_config = {"from_attributes": True}


class BillOrderAdminOut(BillOrderOut):
    user_id: uuid.UUID
    provider: str
    provider_reference: Optional[str] = None
    provider_cost: Optional[Decimal] = None
    failure_reason: Optional[str] = None
    resolved_by: Optional[uuid.UUID] = None
    resolution_note: Optional[str] = None


class ResolveOrder(BaseModel):
    outcome: Literal["completed", "failed"]
    note: Optional[str] = Field(default=None, max_length=300)


class BillPlanAdminOut(BaseModel):
    id: uuid.UUID
    network: str
    plan_code: str
    name: str
    cost_price: Decimal
    selling_price: Decimal
    is_active: bool
    updated_at: datetime

    model_config = {"from_attributes": True}


class BillPlanCreate(BaseModel):
    network: str
    plan_code: str = Field(min_length=1, max_length=64)
    name: str = Field(min_length=2, max_length=80)
    cost_price: Decimal = Field(ge=0, le=10_000_000)
    selling_price: Decimal = Field(gt=0, le=10_000_000)
    is_active: bool = True


class BillPlanUpdate(BaseModel):
    name: Optional[str] = Field(default=None, min_length=2, max_length=80)
    cost_price: Optional[Decimal] = Field(default=None, ge=0, le=10_000_000)
    selling_price: Optional[Decimal] = Field(default=None, gt=0, le=10_000_000)
    is_active: Optional[bool] = None


class BillProviderOut(BaseModel):
    provider: str
    enabled: bool
    configured: bool
    balance: Optional[Decimal] = None
